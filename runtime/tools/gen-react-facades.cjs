// Regenerates src/browser/{react,react-jsx-runtime,react-dom,react-dom-client}.ts
// (ES-module facades over React's CommonJS packages). Run after upgrading React.
const fs = require("fs");
const path = require("path");
const mods = { react: "react", "react-jsx-runtime": "react/jsx-runtime", "react-dom": "react-dom", "react-dom-client": "react-dom/client" };
for (const [file, m] of Object.entries(mods)) {
  const keys = Object.keys(require(m)).filter((k) => /^[A-Za-z_$][\w$]*$/.test(k));
  const src =
    `/**\n * ES-module facade for "${m}" (a CommonJS package).\n * GENERATED by tools/gen-react-facades.cjs — shared via the import map so every\n * card library uses the SAME React instance as the runtime.\n */\n` +
    `import * as ns from "${m}";\n// eslint-disable-next-line @typescript-eslint/no-explicit-any\nconst M: any = (ns as any).default ?? ns;\nexport default M;\n` +
    keys.map((k) => `export const ${k} = M.${k};`).join("\n") + "\n";
  fs.writeFileSync(path.join(__dirname, "../src/browser", `${file}.ts`), src);
}
